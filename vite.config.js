import { defineConfig } from 'vite';

// Сборка трекера v1.
//   root   - входная страница лежит в src/, старый index.html в корне не трогаем
//   base   - относительные адреса: приложение живёт не в корне сайта, а в /Tracker/
//   outDir - готовое приложение кладём в docs/, оттуда его отдаёт GitHub Pages
export default defineConfig({
  root: 'src',
  base: './',
  build: {
    outDir: '../docs',
    emptyOutDir: true,
    // Сжатие отключено намеренно. Сжиматель переименовывает имена, считая их
    // локальными для файла, а модули зовут друг друга по исходным именам -
    // после переименования вызовы попадают не туда. Без сжатия имена сохраняются
    // и всё сходится так же, как в исходном едином файле. Заодно код в docs/
    // остаётся читаемым.
    minify: false,
  },
});
